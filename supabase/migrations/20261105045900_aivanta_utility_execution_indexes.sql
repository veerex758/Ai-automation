-- Complete the server-only utility execution schema with a stable primary key
-- and covering indexes for the Error Trigger event foreign keys.
alter table public.execution_rate_limit_hits
  add column if not exists id bigint generated by default as identity;

do $$
begin
  if not exists (
    select 1 from pg_catalog.pg_constraint
    where conrelid='public.execution_rate_limit_hits'::regclass and contype='p'
  ) then
    alter table public.execution_rate_limit_hits
      add constraint execution_rate_limit_hits_pkey primary key (id);
  end if;
end;
$$;

create index if not exists execution_error_events_workflow_idx
  on public.execution_error_events(workflow_id);
create index if not exists execution_error_events_run_idx
  on public.execution_error_events(workflow_run_id);

comment on table public.execution_rate_limit_hits is
  'Server-only atomic rate-limit hit ledger; access is restricted to service_role.';
comment on table public.execution_error_events is
  'Server-only durable workflow failure outbox; access is restricted to service_role.';
